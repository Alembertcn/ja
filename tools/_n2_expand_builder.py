def emit_py(group_specs):
    lines = [
        "# -*- coding: utf-8 -*-",
        '"""N2 词书扩展组（零基础补 N5–N3 高频 + 主题补全）。由 _n2_expand_builder.py 生成。"""',
        "",
        "def w(word, reading, zh, note=None):",
        '    d = {"word": word, "reading": reading, "zh": zh}',
        "    if note:",
        '        d["note"] = note',
        "    return d",
        "",
        "def grp(gid, title, kind, hint, words):",
        '    return {"id": gid, "title": title, "kind": kind, "hint": hint, "words": words}',
        "",
        "expand_groups = []",
        "",
    ]
    for gid, title, kind, hint, words in group_specs:
        lines.append(
            f'expand_groups.append(grp("{gid}", "{title}", "{kind}", "{hint}", ['
        )
        for word, reading, zh, note in words:
            w_esc = word.replace("\\", "\\\\").replace('"', '\\"')
            r_esc = reading.replace("\\", "\\\\").replace('"', '\\"')
            z_esc = zh.replace("\\", "\\\\").replace('"', '\\"')
            if note:
                n_esc = note.replace("\\", "\\\\").replace('"', '\\"')
                lines.append(f'    w("{w_esc}", "{r_esc}", "{z_esc}", "{n_esc}"),')
            else:
                lines.append(f'    w("{w_esc}", "{r_esc}", "{z_esc}"),')
        lines.append("]))")
        lines.append("")
    return "\n".join(lines)


